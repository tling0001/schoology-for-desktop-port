import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const required = ['APPSTORE_API_PRIVATE_KEY', 'APPSTORE_API_KEY_ID', 'APPSTORE_ISSUER_ID', 'APPLE_TEAM_ID'];
for (const name of required) {
  if (!process.env[name]?.trim()) throw new Error(`Missing required GitHub secret or variable: ${name}`);
}

const keyId = process.env.APPSTORE_API_KEY_ID.trim();
const issuerId = process.env.APPSTORE_ISSUER_ID.trim();
const teamId = process.env.APPLE_TEAM_ID.trim();
const privateKey = process.env.APPSTORE_API_PRIVATE_KEY.replace(/\\n/g, '\n').trim();
const b64url = value => Buffer.from(value).toString('base64url');
const now = Math.floor(Date.now() / 1000);
const unsigned = `${b64url(JSON.stringify({ alg: 'ES256', kid: keyId, typ: 'JWT' }))}.${b64url(JSON.stringify({ iss: issuerId, iat: now, exp: now + 15 * 60, aud: 'appstoreconnect-v1' }))}`;
const signature = crypto.sign('sha256', Buffer.from(unsigned), { key: privateKey, dsaEncoding: 'ieee-p1363' }).toString('base64url');
const token = `${unsigned}.${signature}`;
const outputDir = path.resolve('ios-certificate-output');
await fs.rm(outputDir, { recursive: true, force: true });
await fs.mkdir(outputDir, { recursive: true, mode: 0o700 });

const keyPath = path.join(outputDir, 'Schoology-iOS-Distribution.key');
const csrPath = path.join(outputDir, 'Schoology-iOS-Distribution.csr');
const certDerPath = path.join(outputDir, 'Schoology-iOS-Distribution.cer');
const certPemPath = path.join(outputDir, 'Schoology-iOS-Distribution.pem');
const p12Path = path.join(outputDir, 'Schoology-iOS-Distribution.p12');
execFileSync('openssl', [
  'req', '-new', '-newkey', 'rsa:2048', '-nodes',
  '-keyout', keyPath, '-out', csrPath,
  '-subj', `/CN=Schoology iOS Distribution/O=${teamId}/C=US`
], { stdio: 'inherit' });
await fs.chmod(keyPath, 0o600);
const csr = await fs.readFile(csrPath);
const response = await fetch('https://api.appstoreconnect.apple.com/v1/certificates', {
  method: 'POST',
  headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
  body: JSON.stringify({
    data: {
      type: 'certificates',
      attributes: { certificateType: 'IOS_DISTRIBUTION', csrContent: csr.toString('base64') }
    }
  })
});
const responseText = await response.text();
let payload;
try { payload = JSON.parse(responseText); } catch { payload = { raw: responseText }; }
if (!response.ok) {
  const detail = payload?.errors?.map(error => error.detail || error.title || JSON.stringify(error)).join('; ') || responseText;
  throw new Error(`App Store Connect could not create the iOS distribution certificate (HTTP ${response.status}): ${detail}`);
}
const certificateContent = payload?.data?.attributes?.certificateContent;
if (!certificateContent) throw new Error('App Store Connect returned no certificateContent.');
await fs.writeFile(certDerPath, Buffer.from(certificateContent, 'base64'));
execFileSync('openssl', ['x509', '-inform', 'DER', '-in', certDerPath, '-out', certPemPath], { stdio: 'inherit' });
const p12Password = crypto.randomBytes(24).toString('base64url');
execFileSync('openssl', [
  'pkcs12', '-export', '-inkey', keyPath, '-in', certPemPath,
  '-out', p12Path, '-passout', `pass:${p12Password}`
], { stdio: 'inherit' });
await fs.chmod(p12Path, 0o600);
await fs.rm(keyPath, { force: true });
await fs.rm(csrPath, { force: true });
await fs.rm(certPemPath, { force: true });
const p12Base64 = (await fs.readFile(p12Path)).toString('base64');
await fs.writeFile(path.join(outputDir, 'IOS_CERTIFICATE_P12_BASE64.txt'), p12Base64 + '\n', { mode: 0o600 });
await fs.writeFile(path.join(outputDir, 'IOS_CERTIFICATE_PASSWORD.txt'), p12Password + '\n', { mode: 0o600 });
await fs.writeFile(path.join(outputDir, 'APP_STORE_CONNECT_CERTIFICATE_ID.txt'), String(payload.data.id) + '\n');
await fs.writeFile(path.join(outputDir, 'SETUP-INSTRUCTIONS.txt'), [
  'PRIVATE SIGNING MATERIAL — do not share or commit these files.',
  '',
  '1. In GitHub repository Settings > Secrets and variables > Actions, create/update:',
  '   IOS_CERTIFICATE_P12_BASE64 = full contents of IOS_CERTIFICATE_P12_BASE64.txt',
  '   IOS_CERTIFICATE_PASSWORD = contents of IOS_CERTIFICATE_PASSWORD.txt (without trailing newline)',
  '2. The certificate has already been registered with App Store Connect by the API request.',
  '3. Create the Schoology app record and App ID for bundle ID com.schoologytauri.app if not already present.',
  '4. Register your iPhone UDID, then create an Ad Hoc provisioning profile for com.schoologytauri.app',
  '   using the iOS Distribution certificate generated by this job and include the registered device.',
  '5. Download/install the profile through the workflow action on the next build. Run the workflow again',
  '   with generate_ios_certificate=false (or leave it unchecked) to produce the QR-installable IPA.',
  '',
  'The .p12 and password are sensitive. The workflow artifact expires after one day; download it securely.'
].join('\n') + '\n');
console.log(`Registered iOS distribution certificate ${payload.data.id} and prepared private setup artifact.`);
